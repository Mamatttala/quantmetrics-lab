def test_indicators_match_an_independent_pandas_expression(causal_frame: pd.DataFrame) -> None:
    """A second implementation of the same definition, written differently on purpose."""
    result, _ = compute(
        causal_frame,
        [("sma", "20"), ("bollinger", None), ("realized_vol", "4h")],
    )
    close = causal_frame["close"]
    assert result["sma_20"].to_numpy()[30:] == pytest.approx(
        close.rolling(20).mean().to_numpy()[30:]
    )

    middle = close.rolling(20).mean()
    deviation = close.rolling(20).std(ddof=0)
    assert result["bb_upper_20_2"].to_numpy()[30:] == pytest.approx(
        (middle + 2 * deviation).to_numpy()[30:]
    )
    assert result["bb_lower_20_2"].to_numpy()[30:] == pytest.approx(
        (middle - 2 * deviation).to_numpy()[30:]
    )

    returns = np.log(close / close.shift(1))
    assert result["realized_vol_4h"].to_numpy()[30:] == pytest.approx(
        returns.rolling(4).std(ddof=1).to_numpy()[30:]
    )


def test_ema_matches_an_independent_recursive_filter(causal_frame: pd.DataFrame) -> None:
    """scipy's lfilter, given the same seed, is a different implementation of the recursion."""
    from scipy.signal import lfilter

    result, _ = compute(causal_frame, [("ema", "10")])
    price = causal_frame["close"].to_numpy(dtype=float)
    window = 10
    alpha = 2.0 / (window + 1.0)
    seed = float(price[:window].mean())
    filtered, _ = lfilter(
        [alpha],
        [1.0, -(1.0 - alpha)],
        price[window:],
        zi=[(1.0 - alpha) * seed],
    )
    assert result["ema_10"].to_numpy()[window:] == pytest.approx(filtered)


