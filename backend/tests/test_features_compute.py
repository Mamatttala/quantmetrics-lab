def test_relative_strength_index_uses_wilders_smoothing() -> None:
    """Worked by hand for n = 2 on the seven-bar series.

    Gains:  −, 1, 1, 0, 2, 1, 0     Losses: −, 0, 0, 1, 0, 0, 1
    Wilder(2) seeds at the second observation with the two-bar mean and then halves.
    """
    result, _ = compute(small_frame(), [("rsi", "2")])
    values = result["rsi_2"]
    assert np.isnan(values.iloc[1])
    assert values.iloc[2] == pytest.approx(100.0)  # no losses in the seed window
    assert values.iloc[3] == pytest.approx(50.0)  # avg gain 0.5, avg loss 0.5
    assert values.iloc[4] == pytest.approx(100.0 - 100.0 / 6.0)  # 1.25 against 0.25
    assert values.iloc[5] == pytest.approx(90.0)  # 1.125 against 0.125
    assert values.iloc[6] == pytest.approx(50.0)  # 0.5625 against 0.5625


