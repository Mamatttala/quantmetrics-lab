def test_returns_and_momentum() -> None:
    # The window is written as an interval, not as a bare number, because `roc` and
    # `momentum` take a duration: on a dataset whose bar length is declared, "2" is
    # ambiguous — two bars or two hours — and the catalogue refuses it rather than pick.
    # On this hourly frame "2h" resolves to two bars.
    result, _ = compute(
        small_frame(),
        [("return_1", None), ("log_return_1", None), ("roc", "2h"), ("momentum", "2h")],
    )
    assert result["return_1"].iloc[1] == pytest.approx(0.1)  # 11 / 10 − 1
    assert result["log_return_1"].iloc[1] == pytest.approx(np.log(11.0 / 10.0))
    assert result["roc_2h"].iloc[2] == pytest.approx(0.2)  # 12 / 10 − 1
    assert result["roc_2h"].iloc[5] == pytest.approx(14.0 / 11.0 - 1.0)  # 14 / 11 − 1
    # Bar 6 closes where bar 4 did, so the two-bar return is exactly zero rather than
    # undefined — the case an implementation that guards division by a stale close gets
    # wrong by returning NaN.
    assert result["roc_2h"].iloc[6] == pytest.approx(0.0)
    assert np.isnan(result["roc_2h"].iloc[1])
    assert result["momentum_2h"].iloc[2] == pytest.approx(2.0)  # 12 − 10
    assert result["momentum_2h"].iloc[5] == pytest.approx(3.0)  # 14 − 11
    assert result["momentum_2h"].iloc[6] == pytest.approx(0.0)
    assert np.isnan(result["momentum_2h"].iloc[1])


