def test_range_estimators_against_their_formulas() -> None:
    result, _ = compute(
        small_frame(),
        [("parkinson", "1"), ("garman_klass", "1"), ("rogers_satchell", "1")],
    )
    high, low, close, open_ = 11.0, 9.0, 10.0, 10.0
    assert result["parkinson_1"].iloc[0] == pytest.approx(
        abs(np.log(high / low)) / (2.0 * np.sqrt(np.log(2.0)))
    )
    # open == close, so the body term vanishes and Garman–Klass reduces to the range term.
    assert result["garman_klass_1"].iloc[0] == pytest.approx(
        np.sqrt(0.5 * np.log(high / low) ** 2)
    )
    assert result["rogers_satchell_1"].iloc[0] == pytest.approx(
        np.sqrt(
            np.log(high / close) * np.log(high / open_)
            + np.log(low / close) * np.log(low / open_)
        )
    )


