def test_one_bar_of_volatility_scales_by_the_square_root_of_bars_per_year() -> None:
    """The factor is a convention, so the two conventions are compared explicitly.

    The same hourly returns annualise to a larger number on a 24/7 market than on a
    6.5-hour session, by exactly √(8760 / 1638).
    """
    crypto, _ = compute(hourly_frame(60), [("annualized_vol", "1d")])
    equity, _ = compute(
        hourly_frame(60),
        [("annualized_vol", "1d")],
        context=frame_context(hourly_frame(60), asset_class=AssetClass.EQUITY_SPOT),
    )
    crypto_bars_per_year = 365.0 * 24.0
    equity_bars_per_year = 252.0 * (23400.0 / 3600.0)
    assert crypto["annualized_vol_1d"].iloc[-1] == pytest.approx(
        equity["annualized_vol_1d"].iloc[-1]
        * (crypto_bars_per_year / equity_bars_per_year) ** 0.5,
        rel=1e-9,
    )


def test_annualized_volatility_pins_the_square_root_of_the_annualisation_factor() -> None:
    """The absolute factor, not just the ratio: daily crypto is √365, daily equity √252.

    The window is set to a duration, and the factor is derived from the bar length and
    asset class, so a daily dataset annualises its 1-bar returns by √365 (crypto) or √252
    (equities). Using the realized_volatility column the engine itself produces as the
    reference keeps the check independent of any rolling-window bookkeeping.
    """
    days = pd.date_range("2024-01-01", periods=40, freq="1D", tz="UTC").strftime("%Y-%m-%d")
    crypto_frame = daily_frame(list(days))
    out, _ = compute(
        crypto_frame,
        [("annualized_vol", "7d"), ("realized_vol", "7d")],
        context=frame_context(crypto_frame, timeframe=Timeframe.D1),
    )
    expected = float(out["realized_vol_7d"].iloc[-1]) * 365.0 ** 0.5
    assert float(out["annualized_vol_7d"].iloc[-1]) == pytest.approx(expected, rel=1e-9)

    equity_frame = daily_frame(list(days))
    equity_context = frame_context(
        equity_frame, asset_class=AssetClass.EQUITY_SPOT, timeframe=Timeframe.D1
    )
    out, _ = compute(
        equity_frame, [("annualized_vol", "7d"), ("realized_vol", "7d")], context=equity_context
    )
    expected = float(out["realized_vol_7d"].iloc[-1]) * 252.0 ** 0.5
    assert float(out["annualized_vol_7d"].iloc[-1]) == pytest.approx(expected, rel=1e-9)


