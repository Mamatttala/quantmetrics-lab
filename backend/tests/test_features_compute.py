def test_near_duplicate_columns_are_reported() -> None:
    """Two moving averages of the same ramp are two names for one series.

    The subject is a straight ramp rather than the seeded random walk the rest of this file
    uses, because the correlation the scan reports is then the correlation arithmetic
    predicts rather than a number the test data happens to have: on a linear ramp SMA(5) is
    exactly `close − 2` and SMA(10) exactly `close − 4.5`, so both are linear in the bar
    index and r = 1. Whether a random walk trips the 0.99 threshold depends on its seed,
    which is the wrong thing for a threshold test to be pinning.
    """
    rows = 60
    close = np.arange(100.0, 100.0 + rows)
    frame = pd.DataFrame(
        {
            "open_time": pd.date_range("2024-01-01", periods=rows, freq="1h", tz="UTC"),
            "open": close,
            "high": close + 1.0,
            "low": close - 1.0,
            "close": close,
            "volume": np.full(rows, 10.0),
        }
    )
    _, report = compute(frame, [("sma", "5"), ("sma", "10")])
    pairs = {(entry["a"], entry["b"]) for entry in report["collinearity"]}
    assert ("sma_5", "sma_10") in pairs
    entry = next(e for e in report["collinearity"] if {e["a"], e["b"]} == {"sma_5", "sma_10"})
    assert entry["r"] == pytest.approx(1.0)


def test_no_collinearity_is_reported_for_independent_columns() -> None:
    """A moving average of a random walk and the hour of the day share nothing.

    Picking a genuinely unrelated pair matters: asserting on two price-derived columns
    would make this test about the seed of the test data rather than about the scan.
    """
    _, report = compute(hourly_frame(200), [("sma", "20"), ("hour_of_day", None)])
